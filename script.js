  function parsePolygonPoints(raw) {
    return String(raw || "").trim().split(/\s+/).map(function pair(item) {
      const bits = item.split(",");
      return { x: parseFloat(bits[0]), y: parseFloat(bits[1]) };
    }).filter(function ok(pt) {
      return Number.isFinite(pt.x) && Number.isFinite(pt.y);
    });
  }

  function tracePolygon(ctx, points) {
    if (!points.length) {
      return;
    }
    ctx.beginPath();
    ctx.moveTo(points[0].x, points[0].y);
    for (let i = 1; i < points.length; i += 1) {
      ctx.lineTo(points[i].x, points[i].y);
    }
    ctx.closePath();
  }

  function drawFateRingOnCanvas(ctx, svg, dx, dy, dw, dh) {
    if (!svg || !dw || !dh) {
      return;
    }
    const scaleX = dw / 300;
    const scaleY = dh / 236;
    ctx.save();
    ctx.translate(dx, dy);
    ctx.scale(scaleX, scaleY);

    Array.from(svg.querySelectorAll("polygon")).forEach(function poly(el) {
      const points = parsePolygonPoints(el.getAttribute("points"));
      if (!points.length) {
        return;
      }
      const computed = window.getComputedStyle(el);
      const fill = shareColor(computed.fill);
      const stroke = shareColor(computed.stroke);
      const width = parseFloat(computed.strokeWidth) || 0;
      tracePolygon(ctx, points);
      if (fill && fill !== "none") {
        ctx.fillStyle = fill;
        ctx.fill();
      }
      if (stroke && stroke !== "none" && width > 0) {
        ctx.strokeStyle = stroke;
        ctx.lineWidth = width;
        ctx.lineJoin = "round";
        ctx.stroke();
      }
    });

    Array.from(svg.querySelectorAll("text")).forEach(function label(el) {
      const cls = el.getAttribute("class") || "";
      const x = parseFloat(el.getAttribute("x"));
      const y = parseFloat(el.getAttribute("y"));
      if (!Number.isFinite(x) || !Number.isFinite(y)) {
        return;
      }
      const computed = window.getComputedStyle(el);
      const fill = shareColor(computed.fill) || el.getAttribute("fill") || "#ffffff";
      const fontSize = parseFloat(el.getAttribute("font-size")) || 16;
      const anchor = el.getAttribute("text-anchor") || "start";
      const baseline = el.getAttribute("dominant-baseline") || "auto";
      ctx.save();
      ctx.font = "400 " + fontSize + "px sans-serif";
      ctx.textAlign = anchor === "middle" ? "center" : (anchor === "end" ? "right" : "left");
      if (baseline === "central" || baseline === "middle") {
        ctx.textBaseline = "middle";
      } else if (baseline === "hanging") {
        ctx.textBaseline = "top";
      } else {
        ctx.textBaseline = "alphabetic";
      }
      if (cls.indexOf("fate-ring__star") >= 0) {
        ctx.beginPath();
        ctx.fillStyle = fill;
        ctx.arc(x, y, 3.2, 0, Math.PI * 2);
        ctx.fill();
        ctx.lineWidth = 1.2;
        ctx.strokeStyle = "rgba(6,8,16,0.92)";
        ctx.stroke();
      } else {
        const text = el.textContent || "";
        ctx.lineWidth = 2.4;
        ctx.strokeStyle = "rgba(6,8,16,0.92)";
        ctx.lineJoin = "round";
        ctx.strokeText(text, x, y);
        ctx.fillStyle = fill;
        ctx.fillText(text, x, y);
      }
      ctx.restore();
    });

    const coreEl = svg.querySelector(".fate-ring__core");
    let coreX = 150;
    let coreY = 118;
    let coreR = 4.5;
    if (coreEl) {
      const tag = String(coreEl.tagName || "").toLowerCase();
      if (tag === "circle") {
        coreX = parseFloat(coreEl.getAttribute("cx")) || coreX;
        coreY = parseFloat(coreEl.getAttribute("cy")) || coreY;
        coreR = parseFloat(coreEl.getAttribute("r")) || coreR;
      }
    }
    ctx.beginPath();
    ctx.fillStyle = "#ffc93c";
    ctx.arc(coreX, coreY, coreR, 0, Math.PI * 2);
    ctx.fill();
    ctx.lineWidth = 1.6;
    ctx.strokeStyle = "rgba(6,8,16,0.92)";
    ctx.stroke();

    ctx.restore();
  }

  function fillShareText(ctx, text, x, y, fillStyle, shadows) {
    const layers = shadows || [];
    layers.forEach(function each(shadow) {
      const ox = shadow.x || 0;
      const oy = shadow.y || 0;
      const blur = shadow.blur || 0;
      const color = shadow.color || "transparent";
      ctx.save();
      ctx.fillStyle = color;
      // 硬位移層：畫實心色；柔光層：靠 shadowBlur，最後黑字蓋住實心核，只留光暈
      if (blur > 0) {
        ctx.shadowOffsetX = 0;
        ctx.shadowOffsetY = 0;
        ctx.shadowBlur = blur;
        ctx.shadowColor = color;
      } else {
        ctx.shadowBlur = 0;
        ctx.shadowColor = "transparent";
      }
      ctx.fillText(text, x + ox, y + oy);
      ctx.restore();
    });
    ctx.fillStyle = fillStyle;
    ctx.shadowBlur = 0;
    ctx.shadowColor = "transparent";
    ctx.fillText(text, x, y);
  }

  function waitArtReady(img) {
    if (img && img.complete && img.naturalWidth) {
      return Promise.resolve(img);
    }
    return new Promise(function wait(resolve, reject) {
      if (!img) {
        reject(new Error("image"));
        return;
      }
      const done = function ok() {
        img.removeEventListener("load", done);
        img.removeEventListener("error", fail);
        if (img.naturalWidth) {
          resolve(img);
          return;
        }
        reject(new Error("image"));
      };
      const fail = function bad() {
        img.removeEventListener("load", done);
        img.removeEventListener("error", fail);
        reject(new Error("image"));
      };
      img.addEventListener("load", done);
      img.addEventListener("error", fail);
    });
  }

