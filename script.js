function drawRealmDeck(events, rng, realm) {
  const stages = REALM_STAGES[realm];
  if (!stages) {
    return events || [];
  }
  return sampleStageDeck(events, rng, { stages: stages, count: DRAW_COUNT });
}

function stageNames(stage) {
  return Array.isArray(stage) ? stage : [stage];
}

function sampleStageDeck(events, rng, spec) {
  const used = {};
  const deck = [];
  const count = spec.count > 0 ? spec.count : DRAW_COUNT;
  spec.stages.forEach(function takeStage(stage) {
    const names = {};
    stageNames(stage).forEach(function mark(name) {
      names[name] = true;
    });
    const pool = [];
    (events || []).forEach(function collect(event, index) {
      if (!event || !names[event.stage]) {
        return;
      }
      const key = String(event.id === undefined || event.id === null ? event.stage + "-" + index : event.id);
      if (used[key]) {
        return;
      }
      pool.push({ key: key, event: event });
    });
    const shuffled = shuffleEvents(pool, rng);
    const take = Math.min(count, shuffled.length);
    for (let i = 0; i < take; i += 1) {
      used[shuffled[i].key] = true;
      deck.push(shuffled[i].event);
    }
  });
  return deck;
}

function useScriptDeck(plan, rng, events) {
  if (!events || !events.length) {
    return false;
  }
  plan.clicks = events.length;
  plan.scripted = true;
  plan.total = 100;
  plan.salt = Math.floor(rng() * 997);
  plan.deck = events;
  return true;
}

function shuffleEvents(list, rng) {
  const copy = list.slice();
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    const swap = copy[i];
    copy[i] = copy[j];
    copy[j] = swap;
  }
  return copy;
}

function advanceLife(world) {
  const plan = world.life;
  const index = world.turnCount;
  const before = {
    merit: world.stats.merit,
    greed: world.stats.greed,
    anger: world.stats.anger,
    ignorance: world.stats.ignorance,
  };

  if (world.realmId === "human" || world.realmId === "animal" || world.realmId === "asura") {
    world.clock += plan.steps[index] || 0;
  }

  const effects = {};
  ["merit", "greed", "anger", "ignorance"].forEach(function diff(key) {
    const delta = world.stats[key] - before[key];
    if (delta) {
      effects[key] = delta;
    }
  });
  return Object.keys(effects).length ? effects : null;
}
