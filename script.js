function allocateTenths(weights) {
  const ids = Object.keys(weights);
  const sum = ids.reduce(function add(total, id) {
    return total + weights[id];
  }, 0);
  const budget = 1000;
  const portions = ids.map(function portion(id) {
    return {
      id: id,
      exact: weights[id] / sum * budget,
    };
  });
  const rounded = portions.map(function floorPortion(item) {
    return {
      id: item.id,
      tenths: Math.floor(item.exact),
      frac: item.exact - Math.floor(item.exact),
    };
  });
  let used = rounded.reduce(function addTenths(total, item) {
    return total + item.tenths;
  }, 0);
  const order = rounded.slice().sort(function byFrac(a, b) {
    return b.frac - a.frac;
  });
  let leftover = budget - used;
  for (let i = 0; i < leftover; i += 1) {
    order[i % order.length].tenths += 1;
  }

  const tenthsById = {};
  rounded.forEach(function store(item) {
    tenthsById[item.id] = item.tenths;
  });
  return tenthsById;
}

function applyLockedHiddenSlices(realms, gate, slice) {
  const target = {};
  if (gate === "both" && slice && typeof slice === "object") {
    if (slice.immortal) {
      target.immortal = slice.immortal;
    }
    if (slice.alien) {
      target.alien = slice.alien;
    }
  } else if ((gate === "immortal" || gate === "alien") && typeof slice === "number" && slice > 0) {
    target[gate] = slice;
  } else {
    return realms;
  }
  const lockedIds = Object.keys(target);
  const lockedSum = lockedIds.reduce(function add(total, id) {
    return total + target[id];
  }, 0);
  if (lockedSum <= 0 || lockedSum >= 1000) {
    return realms;
  }
  const others = realms.filter(function free(realm) {
    return target[realm.id] === undefined;
  });
  if (!others.length) {
    return realms;
  }
  const otherSum = others.reduce(function add(total, realm) {
    return total + realm.tenths;
  }, 0);
  const otherBudget = 1000 - lockedSum;
  const portions = others.map(function portion(realm) {
    const exact = otherSum > 0
      ? realm.tenths / otherSum * otherBudget
      : otherBudget / others.length;
    return {
      realm: realm,
      tenths: Math.floor(exact),
      frac: exact - Math.floor(exact),
    };
  });
  let used = portions.reduce(function addTenths(total, item) {
    return total + item.tenths;
  }, 0);
  const order = portions.slice().sort(function byFrac(a, b) {
    return b.frac - a.frac;
  });
  for (let i = 0; i < otherBudget - used; i += 1) {
    order[i % order.length].tenths += 1;
  }
  const byId = {};
  portions.forEach(function store(item) {
    byId[item.realm.id] = item.tenths;
  });
  return realms.map(function merge(realm) {
    const tenths = target[realm.id] !== undefined ? target[realm.id] : byId[realm.id];
    return Object.assign({}, realm, {
      tenths: tenths,
      percent: tenths / 10,
    });
  });
}

