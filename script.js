  function advanceQuiz() {
    if (game.quizIndex < QUESTIONS.length - 1) {
      game.quizIndex += 1;
      renderQuiz();
      quizTitle.focus();
      return;
    }

    const result = computeStats(game.answers, game.birthDate);
    game.seed = result.seed;
    game.stats = result.stats;
    renderResult();
    showScreen("screen-result");
  }

