function diminishedGain(current, delta) {
  if (!delta || delta <= 0) {
    return delta || 0;
  }
  const room = STAT_CAP - (current || 0);
  if (room <= 0) {
    return 0;
  }
  const keep = Math.max(0.08, Math.pow(1 - (current || 0) / STAT_CAP, 1.35));
  return Math.min(room, Math.max(1, Math.round(delta * keep)));
}

function erodeByPoisons(before, next) {
  let surge = 0;
  ["greed", "anger", "ignorance"].forEach(function add(key) {
    const rise = (next[key] || 0) - (before[key] || 0);
    if (rise > 0) {
      surge += rise;
    }
  });
  if (surge <= 0) {
    return;
  }
  const load = ((next.greed || 0) + (next.anger || 0) + (next.ignorance || 0)) / (STAT_CAP * 3);
  const chip = Math.max(1, Math.round(surge * (0.18 + load * 0.28)));
  next.merit = clampStat((next.merit || 0) - chip);
  next.wisdom = clampStat((next.wisdom || 0) - Math.max(1, Math.round(chip * 0.7)));
  if ((before.composure || 0) > 0 || (next.composure || 0) > 0) {
    next.composure = clampStat((next.composure || 0) - Math.max(1, Math.round(chip * 0.45)));
  }
  next.cultivation = clampStat((next.cultivation || 0) - Math.max(1, Math.round(chip * 0.25)));
  next.tech = clampStat((next.tech || 0) - Math.max(1, Math.round(chip * 0.25)));
}

function applyEffects(stats, effects, sets) {
  const before = snapshotStats(stats);
  const next = snapshotStats(stats);
  Object.keys(effects || {}).forEach(function add(key) {
    const current = next[key] || 0;
    const delta = effects[key];
    const gained = delta > 0 ? diminishedGain(current, delta) : delta;
    next[key] = clampStat(current + gained);
  });
  Object.keys(sets || {}).forEach(function assign(key) {
    next[key] = clampStat(sets[key]);
  });
  erodeByPoisons(before, next);
  return next;
}

function describeApplied(before, after, sets) {
  const effects = {};
  ["merit", "wisdom", "greed", "anger", "ignorance", "composure", "spirit"].forEach(function diff(key) {
    if (sets && sets[key] !== undefined) {
      return;
    }
    const delta = (after[key] || 0) - (before[key] || 0);
    if (delta) {
      effects[key] = delta;
    }
  });
  return formatDelta(effects, sets);
}

function formatDelta(effects, sets) {
  const parts = Object.keys(effects || {}).filter(function visible(key) {
    return key !== "cultivation" && key !== "tech" && effects[key];
  }).map(function label(key) {
    const value = effects[key];
    const sign = value > 0 ? "+" : "";
    return (STAT_LABELS[key] || key) + " " + sign + value;
  });
  Object.keys(sets || {}).forEach(function mark(key) {
    if (key === "cultivation" || key === "tech") {
      return;
    }
    const name = STAT_LABELS[key] || key;
    if (sets[key] >= 100) {
      parts.push(name + " 滿");
    } else if (sets[key] <= 0) {
      parts.push(name + " 歸零");
    } else {
      parts.push(name + " 重置");
    }
  });
  return parts.join(" · ");
}

