function diagnoseMenpo(stats) {
  const book = ghostStatBook(stats);
  const axes = [
    { key: "greed", value: book.greed || 0 },
    { key: "anger", value: book.anger || 0 },
    { key: "ignorance", value: book.ignorance || 0 },
    { key: "wisdom", value: book.wisdom || 0 },
    { key: "composure", value: book.composure || 0 },
    { key: "blessing", value: book.blessing || 0 },
  ].sort(function byValue(a, b) {
    if (b.value !== a.value) {
      return b.value - a.value;
    }
    const order = ["greed", "anger", "ignorance", "wisdom", "composure", "blessing"];
    return order.indexOf(a.key) - order.indexOf(b.key);
  });
  const top = axes[0];
  const second = axes[1];
  const near = second
    && second.value > 0
    && second.value >= top.value - 5
    && second.value >= top.value * 0.9;
  const focusKeys = near && menpoGroupFor(second.key) !== menpoGroupFor(top.key)
    ? [top.key, second.key]
    : near && (top.key === "wisdom" || top.key === "composure")
      && (second.key === "wisdom" || second.key === "composure")
      ? ["wisdom", "composure"]
      : [top.key];
  const group = menpoGroupFor(top.key);
  const tier = menpoTierFor(top.value);
  const entry = MENPO_DIAGNOSIS[group] || MENPO_DIAGNOSIS.ignorance;
  let pool = menpoVariantPool((entry && entry[tier]) || entry.mid || entry.mild);
  let source = "single:" + group + ":" + tier;
  if (focusKeys.length === 2) {
    const dualKey = menpoDualKey(focusKeys[0], focusKeys[1]);
    const dual = MENPO_DUAL[dualKey];
    const dualPool = menpoVariantPool(dual && (dual[tier] || dual.mid || dual.mild));
    if (dualPool.length) {
      pool = dualPool;
      source = "dual:" + dualKey + ":" + tier;
    }
  }
  const salt = [
    source,
    axes.map(function part(row) {
      return row.key + "=" + row.value;
    }).join(","),
  ].join("|");
  const pack = pickMenpoVariant(pool, salt);
  const pulse = focusKeys.map(function name(key) {
    return MENPO_STAT_LABELS[key] || key;
  }).join(" · ");
  return {
    group: group,
    tier: tier,
    keys: focusKeys,
    pulse: pulse,
    focus: "偏高脈象：" + pulse,
    chief: pack.chief,
    rx: pack.rx,
    label: entry.label || MENPO_STAT_LABELS[group] || group,
  };
}

function endingListText(pack, world) {
  if (!pack || !pack.endings || !pack.endings.length) {
    return "";
  }
  const book = ghostStatBook(world.stats);
  const matched = pack.endings.filter(function keep(row) {
    return settlementHits(row, book);
  });
  if (!matched.length) {
    rememberEndingPlate(world, null);
    return "";
  }
  matched.sort(function louder(a, b) {
    const priority = (b.priority || 0) - (a.priority || 0);
    if (priority) {
      return priority;
    }
    const excess = ghostFinaleExcess(b, book) - ghostFinaleExcess(a, book);
    if (excess) {
      return excess;
    }
    if (a.stat && b.stat) {
      return (book[b.stat] || 0) - (book[a.stat] || 0);
    }
    return 0;
  });
  const finale = matched[0];
  rememberEndingPlate(world, finale);
  return "【" + finale.name + "】" + (finale.text || "");
}

