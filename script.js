function assignGateSlice(world) {
  const gate = world.life.gateRealm;
  if (!gate) {
    world.life.gateSlice = 0;
    return;
  }
  const realms = buildRealms(world.stats, true, gate);
  if (gate === "both") {
    const book = { immortal: 0, alien: 0 };
    realms.forEach(function read(realm) {
      if (realm.id === "immortal" || realm.id === "alien") {
        book[realm.id] = realm.tenths;
      }
    });
    world.life.gateSlice = book;
    return;
  }
  let tenths = 0;
  realms.forEach(function read(realm) {
    if (realm.id === gate) {
      tenths = realm.tenths;
    }
  });
  world.life.gateSlice = tenths;
}

