// 結局門檻語意（含邊界）：
// - min: value >= min（含等號）
// - max: value <= max（含等號）
// - above: value > above（不含等號；above:99 表示需 >=100）
// 銜接範例：patron max greed 99 與 gluttony above greed 99 無縫相接，不會卡在 99。
function ghostRuleHits(rule, book) {
  const min = rule.min || {};
  const above = rule.above || {};
  const max = rule.max || {};
  const keys = Object.keys(min).concat(Object.keys(above), Object.keys(max));
  return keys.every(function pass(key) {
    const value = book[key] || 0;
    if (min[key] !== undefined && value < min[key]) {
      return false;
    }
    if (above[key] !== undefined && value <= above[key]) {
      return false;
    }
    if (max[key] !== undefined && value > max[key]) {
      return false;
    }
    return true;
  });
}

function ghostFinaleExcess(rule, book) {
  let score = 0;
  Object.keys(rule.above || {}).forEach(function add(key) {
    score += (book[key] || 0) - rule.above[key];
  });
  Object.keys(rule.min || {}).forEach(function add(key) {
    score += (book[key] || 0) - rule.min[key];
  });
  return score;
}

function statSpread(book) {
  const keys = ["greed", "ignorance", "anger", "composure", "wisdom", "blessing"];
  let hi = 0;
  let lo = 0;
  keys.forEach(function measure(key, index) {
    const value = book[key] || 0;
    if (index === 0 || value > hi) {
      hi = value;
    }
    if (index === 0 || value < lo) {
      lo = value;
    }
  });
  return hi - lo;
}

function settlementHits(row, book) {
  if (!ghostRuleHits(row, book)) {
    return false;
  }
  if (row.balanced !== undefined && statSpread(book) > row.balanced) {
    return false;
  }
  return true;
}

